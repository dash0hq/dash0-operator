// Keys of the Secret that holds the operator-managed webhook certificates.
const (
	keyCaBundle          = "ca.crt"
	keyActiveCaCert      = "active-ca.crt"
	keyActiveCaKey       = "active-ca.key"
	keyPendingCaCert     = "pending-ca.crt"
	keyPendingCaKey      = "pending-ca.key"
	keyRotationStartedAt = "rotation-started-at"
	keyPreviousCaCerts   = "previous-ca.crt"
	keyRetainedChartCas  = "retained-chart-ca.crt"
	keyRetainedCerts     = "retained-ca.crt"
	keyRetainedSince     = "retained-since"
	keyServingCert       = "tls.crt"
	keyServingKey        = "tls.key"
)

// material is the complete certificate state that is persisted in the Secret.
type material struct {
	activeCa *keyPair

	// pendingCa is only set during a CA rotation; it is already part of the bundle, but does not sign anything yet.
	pendingCa         *keyPair
	rotationStartedAt time.Time

	// previousCas are CAs that have been replaced by a rotation; they stay in the bundle until they have expired.
	previousCas []*x509.Certificate

	// retainedChartCas are CAs generated by older chart versions. They stay in the bundle until they have expired, so
	// that a rollback to a chart version before the operator-managed certificates works.
	retainedChartCas []*x509.Certificate

	// retainedCerts are other foreign certificates (e.g. from cert-manager), which are removed once the rollout of the
	// operator deployment is complete and foreignCertRetention has passed since retainedSince.
	retainedCerts []*x509.Certificate
	retainedSince time.Time

	// serving is nil if the stored serving certificate is missing or unusable.
	serving *keyPair
}

// rememberedMaterial is the last material this process has persisted or adopted, together with the UID of the Secret
// it was stored in. It is used to restore the Secret data if it has been wiped while the Secret object was kept.
type rememberedMaterial struct {
	secretUid types.UID
	data      map[string][]byte
}

func (m *material) bundleCerts() []*x509.Certificate {
	var certs []*x509.Certificate
	certs = appendUnique(certs, m.activeCa.cert)
	if m.pendingCa != nil {
		certs = appendUnique(certs, m.pendingCa.cert)
	}
	certs = appendUnique(certs, m.previousCas...)
	certs = appendUnique(certs, m.retainedChartCas...)
	certs = appendUnique(certs, m.retainedCerts...)
	// A stable order keeps the bundle unchanged when the pending CA becomes active.
	slices.SortStableFunc(certs, func(a *x509.Certificate, b *x509.Certificate) int {
		if byNotBefore := a.NotBefore.Compare(b.NotBefore); byNotBefore != 0 {
			return byNotBefore
		}
		return bytes.Compare(a.Raw, b.Raw)
	})
	return certs
}

// bundle returns the PEM-encoded CA bundle that is injected into the webhook configurations and the CRD.
func (m *material) bundle() []byte {
	return encodeCertificates(m.bundleCerts())
}

func (m *material) toSecretData() map[string][]byte {
	data := map[string][]byte{
		keyCaBundle:     m.bundle(),
		keyActiveCaCert: m.activeCa.certPem,
		keyActiveCaKey:  m.activeCa.keyPem,
	}
	if m.pendingCa != nil {
		data[keyPendingCaCert] = m.pendingCa.certPem
		data[keyPendingCaKey] = m.pendingCa.keyPem
		data[keyRotationStartedAt] = []byte(m.rotationStartedAt.UTC().Format(time.RFC3339))
	}
	if len(m.previousCas) > 0 {
		data[keyPreviousCaCerts] = encodeCertificates(m.previousCas)
	}
	if len(m.retainedChartCas) > 0 {
		data[keyRetainedChartCas] = encodeCertificates(m.retainedChartCas)
	}
	if len(m.retainedCerts) > 0 {
		data[keyRetainedCerts] = encodeCertificates(m.retainedCerts)
		data[keyRetainedSince] = []byte(m.retainedSince.UTC().Format(time.RFC3339))
	}
	if m.serving != nil {
		data[keyServingCert] = m.serving.certPem
		data[keyServingKey] = m.serving.keyPem
	}
	return data
}

// materialFromSecretData parses the Secret data. It returns an error if the data does not contain a usable active CA
// (missing, unparsable, key mismatch, or expired). An unusable serving certificate or pending CA does not make the
// material unusable, they are replaced by maintain.
func materialFromSecretData(data map[string][]byte, now time.Time) (*material, error) {
	if len(data) == 0 {
		return nil, fmt.Errorf("the secret has no data")
	}
	activeCa, err := parseKeyPair(data[keyActiveCaCert], data[keyActiveCaKey])
	if err != nil {
		return nil, fmt.Errorf("the active CA is not usable: %w", err)
	}
	if !activeCa.cert.IsCA {
		return nil, fmt.Errorf("the active CA certificate is not a CA certificate")
	}
	if isExpired(activeCa.cert, now) {
		return nil, fmt.Errorf("the active CA has expired at %s", activeCa.cert.NotAfter.Format(time.RFC3339))
	}
	m := &material{
		activeCa:         activeCa,
		previousCas:      parseCertificates(data[keyPreviousCaCerts]),
		retainedChartCas: parseCertificates(data[keyRetainedChartCas]),
		retainedCerts:    parseCertificates(data[keyRetainedCerts]),
		retainedSince:    parseTimestamp(data[keyRetainedSince], now),
	}
	if pendingCa, err := parseKeyPair(data[keyPendingCaCert], data[keyPendingCaKey]); err == nil &&
		pendingCa.cert.IsCA && !isExpired(pendingCa.cert, now) {
		m.pendingCa = pendingCa
		m.rotationStartedAt = parseTimestamp(data[keyRotationStartedAt], now)
	}
	if serving, err := parseKeyPair(data[keyServingCert], data[keyServingKey]); err == nil &&
		verifyServingCertChain(serving.cert, activeCa.cert, now) == nil {
		m.serving = serving
	}
	return m, nil
}

// parseTimestamp parses an RFC 3339 timestamp; a missing or invalid value is treated as now, which only delays the
// actions that depend on it.
func parseTimestamp(raw []byte, now time.Time) time.Time {
	if len(raw) == 0 {
		return now
	}
	parsed, err := time.Parse(time.RFC3339, string(raw))
	if err != nil {
		return now
	}
	return parsed
}

// retentionCandidates are the certificates that the injection targets and the Secret of older chart versions trust,
// apart from the ones the operator has created.
type retentionCandidates struct {
	chartCas []*x509.Certificate
	other    []*x509.Certificate
}

// add sorts the given certificates into the candidates. Certificates created by the operator are skipped: when they
// show up here, the Secret holding their key has been deleted, possibly deliberately because the key has leaked.
func (c *retentionCandidates) add(certs []*x509.Certificate, fromChartSecret bool, now time.Time) {
	for _, cert := range certs {
		if isExpired(cert, now) || isOperatorCreated(cert) {
			continue
		}
		if fromChartSecret || isLegacyChartCa(cert) {
			c.chartCas = appendUnique(c.chartCas, cert)
		} else {
			c.other = appendUnique(c.other, cert)
		}
	}
	// A certificate that has been found in a bundle and in the chart secret only needs to be listed once.
	var other []*x509.Certificate
	for _, cert := range c.other {
		if !containsCertificate(c.chartCas, cert) {
			other = append(other, cert)
		}
	}
	c.other = other
}

func generateMaterial(dnsNames []string, candidates retentionCandidates, now time.Time) (*material, error) {
	activeCa, err := generateCa(now)
	if err != nil {
		return nil, err
	}
	serving, err := issueServingCert(activeCa, dnsNames, now)
	if err != nil {
		return nil, err
	}
	return &material{
		activeCa:         activeCa,
		retainedChartCas: candidates.chartCas,
		retainedCerts:    candidates.other,
		retainedSince:    now,
		serving:          serving,
	}, nil
}

// retainChartCas adds the given CAs of older chart versions that the bundle does not contain yet, and returns how many
// have been added.
func (m *material) retainChartCas(chartCas []*x509.Certificate) int {
	bundleCerts := m.bundleCerts()
	added := 0
	for _, ca := range chartCas {
		if !containsCertificate(bundleCerts, ca) {
			m.retainedChartCas = append(m.retainedChartCas, ca)
			added++
		}
	}
	return added
}

// maintainInput holds what maintain needs besides the material itself.
type maintainInput struct {
	now      time.Time
	dnsNames []string
	// rolloutComplete reports whether the rollout of the operator deployment is complete. It is only called when
	// retained foreign certificates are due for removal.
	rolloutComplete func() bool
}

// maintenanceResult describes the changes maintain has made.
type maintenanceResult struct {
	changes       []string
	bundleChanged bool
	// retentionOverdue is set when retained foreign certificates are due for removal, but the rollout of the operator
	// deployment is not complete yet.
	retentionOverdue bool
}

// maintain renews the serving certificate, starts a CA rotation, and removes retained and expired certificates when
// they are due. It does not switch to a pending CA, see switchToPendingCa.
func (m *material) maintain(in maintainInput) (maintenanceResult, error) {
	result := maintenanceResult{}

	if m.pendingCa == nil && in.now.Add(caRotationLeadTime).After(m.activeCa.cert.NotAfter) {
		pendingCa, err := generateCa(in.now)
		if err != nil {
			return result, err
		}
		m.pendingCa = pendingCa
		m.rotationStartedAt = in.now
		result.changes = append(result.changes, "started a CA rotation")
		result.bundleChanged = true
	}

	if len(m.retainedCerts) > 0 && !in.now.Before(m.retainedSince.Add(foreignCertRetention)) {
		if in.rolloutComplete() {
			m.retainedCerts = nil
			result.changes = append(result.changes, "removed retained foreign certificates")
			result.bundleChanged = true
		} else {
			result.retentionOverdue = true
		}
	}

	// Expired certificates are inert, so they are only removed together with a bundle change that happens anyway.
	// Every bundle change can cause a short window for GitOps tools that re-apply a stale bundle.
	if result.bundleChanged {
		m.previousCas = withoutExpired(m.previousCas, in.now)
		m.retainedChartCas = withoutExpired(m.retainedChartCas, in.now)
		m.retainedCerts = withoutExpired(m.retainedCerts, in.now)
	}

	if change, err := m.ensureServingCert(in.dnsNames, in.now); err != nil {
		return result, err
	} else if change != "" {
		result.changes = append(result.changes, change)
	}
	return result, nil
}

// ensureServingCert issues a new serving certificate if there is none, if DNS names are missing, or if it is due for
// renewal. Missing DNS names are added to the existing ones, so that replicas with different webhook service names
// during a rollout do not replace each other's certificate back and forth.
func (m *material) ensureServingCert(dnsNames []string, now time.Time) (string, error) {
	if m.serving == nil {
		serving, err := issueServingCert(m.activeCa, dnsNames, now)
		if err != nil {
			return "", err
		}
		m.serving = serving
		return "issued a serving certificate", nil
	}
	if missing := missingDnsNames(m.serving.cert, dnsNames); len(missing) > 0 {
		serving, err := issueServingCert(m.activeCa, append(append([]string{}, m.serving.cert.DNSNames...), missing...), now)
		if err != nil {
			return "", err
		}
		m.serving = serving
		return fmt.Sprintf("re-issued the serving certificate with the additional DNS names %v", missing), nil
	}
	// Only renew if the new certificate would actually be valid longer; close to the expiry of the active CA, the
	// validity is capped and a renewal would not gain anything.
	if now.Add(servingCertRenewBefore).After(m.serving.cert.NotAfter) &&
		servingCertNotAfter(m.activeCa, now).After(m.serving.cert.NotAfter) {
		serving, err := issueServingCert(m.activeCa, dnsNames, now)
		if err != nil {
			return "", err
		}
		m.serving = serving
		return "renewed the serving certificate", nil
	}
	return "", nil
}

// switchDecision is the result of evaluating whether a pending CA rotation can complete.
type switchDecision int

const (
	noRotationPending switchDecision = iota
	rotationWaiting
	rotationBlocked
	rotationSwitch
	rotationForcedSwitch
)

// evaluateSwitch decides whether the pending CA can become active. allTargetsInjected reports whether every injection
// target already carries the current bundle, which contains the pending CA.
func (m *material) evaluateSwitch(allTargetsInjected bool, now time.Time) switchDecision {
	if m.pendingCa == nil {
		return noRotationPending
	}
	if now.Add(forcedSwitchLeadTime).After(m.activeCa.cert.NotAfter) {
		if allTargetsInjected {
			return rotationSwitch
		}
		return rotationForcedSwitch
	}
	if now.Before(m.rotationStartedAt.Add(minimumRotationAge)) {
		return rotationWaiting
	}
	if !allTargetsInjected {
		return rotationBlocked
	}
	return rotationSwitch
}

// switchToPendingCa makes the pending CA the active CA, and issues a serving certificate signed by it. The bundle does
// not change, since the pending CA is already part of it.
func (m *material) switchToPendingCa(dnsNames []string, now time.Time) error {
	if m.pendingCa == nil {
		return fmt.Errorf("there is no pending CA")
	}
	names := dnsNames
	if m.serving != nil {
		names = append(append([]string{}, m.serving.cert.DNSNames...), missingDnsNames(m.serving.cert, dnsNames)...)
	}
	serving, err := issueServingCert(m.pendingCa, names, now)
	if err != nil {
		return err
	}
	m.previousCas = appendUnique(m.previousCas, m.activeCa.cert)
	m.activeCa = m.pendingCa
	m.pendingCa = nil
	m.rotationStartedAt = time.Time{}
	m.serving = serving
	return nil
}

func cloneData(data map[string][]byte) map[string][]byte {
	cloned := make(map[string][]byte, len(data))
	for key, value := range data {
		cloned[key] = append([]byte(nil), value...)
	}
	return cloned
}

func dataEqual(a map[string][]byte, b map[string][]byte) bool {
	return maps.EqualFunc(a, b, func(x []byte, y []byte) bool {
		return string(x) == string(y)
	})
}
